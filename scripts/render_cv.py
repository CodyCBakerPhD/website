#!/usr/bin/env python3
"""Render the rubrics of the full CV and the one-page resume from the records.

The site keeps its summaries, highlighted projects, curated datasets and
publications as one JSON record per file under summaries/, projects/,
datasets/ and publications/. This script renders those records as the LaTeX
rubrics that the CV and resume under cv/ include, as configured in
cv/records.toml, so that they and the site say the same thing. The macros the
rubrics use (cvitems, \\cvtitle and the like) are defined in
cv/resume_settings.sty, which sets how they look. The rubrics are built
rather than committed (see docs/development.md).

    python3 scripts/render_cv.py

Requires Python 3.11 or later and nothing beyond the standard library.
"""

import json
import re
import sys
import tomllib
from collections.abc import Callable, Iterable
from dataclasses import dataclass, field
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
CV_DIR = REPO_ROOT / "cv"
CONFIG_FILE = CV_DIR / "records.toml"
# The order the website shows each directory's records in, which a section
# follows with show = "site".
DISPLAY_ORDER_FILE = REPO_ROOT / "src" / "build" / "display-order.json"
WEBSITE_URL = "https://www.codycbakerphd.com"


class SyncError(Exception):
    """A problem with the records or the configuration; the message lists every one found."""


# --------------------------------------------------------------------------- #
# Plain text from the records to LaTeX
# --------------------------------------------------------------------------- #

_LATEX_SPECIALS = {
    "\\": r"\textbackslash{}",
    "&": r"\&",
    "%": r"\%",
    "$": r"\$",
    "#": r"\#",
    "_": r"\_",
    "{": r"\{",
    "}": r"\}",
    "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
}
_LATEX_SPECIALS_PATTERN = re.compile("|".join(re.escape(char) for char in _LATEX_SPECIALS))


def latex_text(text: str) -> str:
    """Escapes record text for LaTeX, rendering **double asterisks** as bold and straight quotes as curly ones."""
    escaped = _LATEX_SPECIALS_PATTERN.sub(lambda match: _LATEX_SPECIALS[match.group()], text)
    escaped = re.sub(r'"([^"]*)"', r"``\1''", escaped)
    return re.sub(r"\*\*(.+?)\*\*", r"\\textbf{\1}", escaped)


def latex_url(url: str) -> str:
    """Escapes the characters that break the URL argument of \\href."""
    return re.sub(r"([#%\\{}])", r"\\\1", url)


# Words ending in a period that do not end a sentence.
# fmt: off
_ABBREVIATIONS = {
    "e.g.", "i.e.", "etc.", "vs.", "cf.", "ca.", "approx.", "al.", "Ph.D.",
    "Fig.", "Figs.", "Eq.", "Ref.", "Refs.", "No.", "Vol.", "pp.",
    "Dr.", "Prof.", "Mr.", "Ms.", "Mrs.", "Jr.", "Sr.", "Inc.", "Ltd.", "Corp.", "Co.",
}
# fmt: on
_SENTENCE_BREAK = re.compile(r"""[.!?]["')\]]*\s+(?=(?:\*\*)?["(\[]?[A-Za-z0-9])""")


def split_sentences(paragraph: str) -> list[str]:
    """
    Splits a paragraph into sentences: the resume gives each claim its own bullet, as it did before the sync.

    A sentence may start with a lowercase letter, as a product name such as neuroconv does. A period does not end
    one after an abbreviation, an initial ("J. Smith") or letters between periods ("U.S.", "a.k.a."), even inside
    brackets or quotes, nor does an ellipsis.
    """
    sentences = []
    start = 0
    for match in _SENTENCE_BREAK.finditer(paragraph):
        candidate = paragraph[start : match.end()].strip()
        last_word = candidate.split()[-1].strip("\"'()[]*")
        # A break inside a **bold** span would split the span across bullets.
        if (
            last_word in _ABBREVIATIONS
            or re.fullmatch(r"(?:[A-Za-z]\.)+", last_word)
            or last_word.endswith("..")
            or candidate.count("**") % 2
        ):
            continue
        sentences.append(candidate)
        start = match.end()
    sentences.append(paragraph[start:].strip())
    return [sentence for sentence in sentences if sentence]


# --------------------------------------------------------------------------- #
# LaTeX building blocks, styled by the macros of cv/resume_settings.sty
# --------------------------------------------------------------------------- #

ENTRY_SEPARATOR = "%\n%\n%"


def header_comment(records_dir: str) -> str:
    return (
        f"% Generated by scripts/render_cv.py from the {records_dir}/ records, and not\n"
        f"% committed. Change the records, or this file's section in cv/{CONFIG_FILE.name},\n"
        f"% then rerun the script.\n"
    )


def bullet_list(items: Iterable[str]) -> str:
    return "\n".join([r"\begin{cvitems}", "\n".join(rf"\item {item}" for item in items), r"\end{cvitems}"])


def description_bullets(description: list[str]) -> list[str]:
    return [latex_text(sentence) for paragraph in description for sentence in split_sentences(paragraph)]


def rubric(title: str, entries: list[str], intro: str | None = None) -> str:
    lines = [rf"\begin{{rubric}}{{{title}}}", ""]
    if intro:
        lines.extend([r"\text{", f"    {intro}", "}"])
    lines.extend([ENTRY_SEPARATOR, f"\n{ENTRY_SEPARATOR}\n".join(entries), ENTRY_SEPARATOR, r"\end{rubric}"])
    return "\n".join(lines) + "\n"


def rubric_title(icon: str, name: str) -> str:
    return rf"\cvrubric{{{icon}}}{{{name}}}"


def website_link(page: str) -> str:
    """Links to one page of the website, which has a page per record section, by its address without '.html'."""
    return rf"\href{{{WEBSITE_URL}/{page}}}{{codycbakerphd.com/{page}}}"


def keywords(words: Iterable[str]) -> str:
    return r"\cvkeywords{" + r"\cvsep ".join(latex_text(word) for word in words) + "}"


def year_range(start: str, end: str | None) -> str:
    """The years of a record's start_date and end_date, which runs to the present while it is ongoing."""
    start_year = start[:4]
    end_year = end[:4] if end else "Present"
    return start_year if end_year == start_year else f"{start_year} -- {end_year}"


# --------------------------------------------------------------------------- #
# Renderers, one per record directory
# --------------------------------------------------------------------------- #


def render_project(record_id: str, project: dict, compact: bool) -> str:
    bullets = []
    if "contribution" in project and not compact:
        bullets.append(rf"\emph{{Contribution:}} {latex_text(project['contribution'])}")
    bullets.extend(description_bullets(project["description"]))
    if compact:
        bullets = bullets[:1]
    name = rf"\href{{{latex_url(project['url'])}}}{{{latex_text(project['name'])}}}"
    lines = [
        f"% {record_id}.json, record_version {project['record_version']}",
        rf"\entry*[{year_range(project['start_date'], project.get('end_date'))}]",
        rf"\cvtitle{{{name}}}{{{latex_text(project['role'])}}}",
    ]
    # Tags are written "theme:tag"; the resume shows the tags alone, as keywords.
    if project.get("tags") and not compact:
        lines.append(keywords(tag.split(":", 1)[1] for tag in project["tags"]))
    lines.append(bullet_list(bullets))
    return "\n".join(lines)


def render_projects(records: list[tuple[str, dict]], compact: bool) -> str:
    return rubric(
        title=rubric_title(r"\faFlask", "Selected Projects" if compact else "Highlighted Projects"),
        intro=(
            None
            if compact
            else (
                "Below are the most recent highlights of my major work. "
                f"You can find the full listing at {website_link('projects')}"
            )
        ),
        entries=[render_project(record_id, record, compact) for record_id, record in records],
    )


# The website's labels for a dataset's links, in the order it shows them.
DATASET_LINK_LABELS = {
    "manuscript": "Manuscript",
    "dataset": "Dataset",
    "notebook": "Jupyter Notebook",
    "code": "Conversion Code",
}


def render_dataset(record_id: str, dataset: dict, compact: bool) -> str:
    source = ", ".join(latex_text(dataset[key]) for key in ("group", "institution") if key in dataset)
    lines = [
        f"% {record_id}.json, record_version {dataset['record_version']}",
        r"\entry*[]",
        rf"\cvtitle{{{latex_text(dataset['name'])}}}{{{latex_text(dataset['role'])}}}",
        rf"\cvdetail{{{source}\cvsep {latex_text(dataset['modality'])}}}",
    ]
    links = dataset.get("links", {})
    hrefs = [
        rf"\href{{{latex_url(links[key])}}}{{{label}}}" for key, label in DATASET_LINK_LABELS.items() if key in links
    ]
    if hrefs:
        lines.append(r"\cvdetail{" + r"\cvsep ".join(hrefs) + "}")
    bullets = description_bullets(dataset["description"])
    lines.append(bullet_list(bullets[:1] if compact else bullets))
    return "\n".join(lines)


def render_datasets(records: list[tuple[str, dict]], compact: bool) -> str:
    return rubric(
        title=rubric_title(r"\faDatabase", "Selected Data Curation" if compact else "Data Curation"),
        intro=(
            None
            if compact
            else (
                "Below are among the more notable of the dozens of datasets I have helped manage, curate, and publish. "
                f"You can find the full listing at {website_link('data-curation')}"
            )
        ),
        entries=[render_dataset(record_id, record, compact) for record_id, record in records],
    )


# The website's heading for each kind of publication, in the order it shows the groups.
PUBLICATION_KINDS = {
    "article": "Journal Articles",
    "presentation": "Conference Presentations",
    "workshop": "Workshops",
}

# The resume owner's name as it appears in the author lists of the records.
OWNER = "C. Baker"


def author_list(authors: list[str], et_al: bool) -> str:
    """'A', 'A and B', 'A, B, and C', or 'A, B, et al.' when the record lists only the leading authors."""
    names = [r"\cvowner{" + latex_text(author) + "}" if author == OWNER else latex_text(author) for author in authors]
    if et_al:
        return ", ".join(names) + ", et al."
    if len(names) <= 2:
        return " and ".join(names)
    return ", ".join(names[:-1]) + ", and " + names[-1]


def sentence(text: str) -> str:
    """Ends a part of a citation with a period, unless it already ends a sentence."""
    return text if re.search(r"[.?!]$", text) else f"{text}."


def render_publication(record_id: str, publication: dict, year: str, compact: bool) -> str:
    title = f"``{sentence(latex_text(publication['name']))}''"
    # A compact entry links its title to the DOI, rather than spelling the DOI out.
    if compact and "doi" in publication:
        title = rf"\href{{{latex_url(publication['doi'])}}}{{{title}}}"
    parts = [
        sentence(author_list(publication["authors"], publication.get("et_al", False))),
        title,
        rf"\emph{{{latex_text(publication['venue'])}}}.",
    ]
    if "note" in publication:
        parts.append(sentence(latex_text(publication["note"])))
    if "doi" in publication and not compact:
        doi = publication["doi"].removeprefix("https://doi.org/")
        parts.append(rf"\cvdoi{{{latex_url(publication['doi'])}}}{{{latex_text(doi)}}}")
    return "\n".join(
        [f"% {record_id}.json, record_version {publication['record_version']}", rf"\entry*[{year}]", " ".join(parts)]
    )


def publication_entries(records: list[tuple[str, dict]], compact: bool) -> list[str]:
    entries = []
    previous_year = None
    for record_id, record in records:
        year = record["date"][:4]
        # Each year is shown once, beside the first of its publications.
        entries.append(render_publication(record_id, record, year if year != previous_year else "", compact))
        previous_year = year
    return entries


def render_publications(records: list[tuple[str, dict]], compact: bool) -> str:
    """Groups the publications under a heading per kind, as the website does, keeping their order within each.

    A compact section lists its few publications in order, without the headings.
    """
    if compact:
        return rubric(
            title=rubric_title(r"\faBook", "Selected Publications"), entries=publication_entries(records, compact=True)
        )
    unknown = sorted({record["kind"] for _, record in records} - set(PUBLICATION_KINDS))
    if unknown:
        raise SyncError(f"publications: no heading for the kinds {unknown}; add them to PUBLICATION_KINDS")
    groups = []
    for kind, heading in PUBLICATION_KINDS.items():
        entries = publication_entries(
            [(record_id, record) for record_id, record in records if record["kind"] == kind], compact=False
        )
        if entries:
            groups.append(f"\\subrubric{{{heading}}}\n" + f"\n{ENTRY_SEPARATOR}\n".join(entries))
    return rubric(title=rubric_title(r"\faBook", "Publications"), entries=groups)


def render_summaries(records: list[tuple[str, dict]], compact: bool) -> str:
    """The Summary rubric, from the one summary a section shows, as paragraphs.

    A compact summary runs the first sentence of each paragraph together into one.
    """
    [(record_id, summary)] = records
    if compact:
        paragraphs = [" ".join(latex_text(split_sentences(paragraph)[0]) for paragraph in summary["description"])]
    else:
        paragraphs = [latex_text(paragraph) for paragraph in summary["description"]]
    title = rubric_title(r"\faInfoCircle", "Summary")
    return (
        "\n".join(
            [
                f"% {record_id}.json, record_version {summary['record_version']}",
                rf"\begin{{rubric}}{{{title}}}",
                "",
                r"\text{",
                "\n\n    \\vspace*{2.5mm}\n\n".join(f"    {paragraph}" for paragraph in paragraphs),
                "}",
                "",
                r"\end{rubric}",
            ]
        )
        + "\n"
    )


@dataclass(frozen=True)
class RecordType:
    # Renders the selected records; the flag asks for the compact form of a one-page resume.
    render: Callable[[list[tuple[str, dict]], bool], str]
    required: tuple[str, ...]
    # Whether a section of these records shows exactly one of them.
    shows_one: bool = False


# Required fields are those of the website's LinkML schema (schemas/records.yaml)
# that the renderers read without a fallback.
RECORD_TYPES = {
    "summaries": RecordType(render_summaries, ("record_version", "description"), shows_one=True),
    "projects": RecordType(render_projects, ("record_version", "name", "role", "description", "url", "start_date")),
    "datasets": RecordType(render_datasets, ("record_version", "name", "role", "description", "group", "modality")),
    "publications": RecordType(render_publications, ("record_version", "name", "kind", "authors", "date", "venue")),
}


# --------------------------------------------------------------------------- #
# Configuration and records
# --------------------------------------------------------------------------- #


@dataclass
class Section:
    output: Path
    records: str
    show: list[str]
    omit: list[str] = field(default_factory=list)
    compact: bool = False
    # Whether `show` is the website's display order rather than a list of its own.
    follows_site: bool = False


def load_sections(config_file: Path) -> list[Section]:
    config = tomllib.loads(config_file.read_text(encoding="utf-8"))
    display_order = json.loads(DISPLAY_ORDER_FILE.read_text(encoding="utf-8"))
    sections = []
    problems = []
    for index, entry in enumerate(config.get("section", [])):
        where = f"{config_file.name}, section {index + 1}"
        unknown = set(entry) - {"output", "records", "show", "omit", "compact"}
        if unknown:
            problems.append(f"{where}: unknown keys {sorted(unknown)}")
        if entry.get("records") not in RECORD_TYPES:
            problems.append(f"{where}: 'records' must be one of {sorted(RECORD_TYPES)}")
        if not isinstance(entry.get("compact", False), bool):
            problems.append(f"{where}: 'compact' must be true or false")
        follows_site = entry.get("show") == "site"
        if follows_site:
            if entry.get("records") not in display_order:
                problems.append(
                    f"{where}: the website has no display order for {entry.get('records')!r}, so 'show' must list IDs"
                )
                continue
            if entry.get("omit"):
                problems.append(
                    f"{where}: a section that follows the website's order shows every record, so 'omit' must be empty"
                )
                continue
            entry = {**entry, "show": display_order[entry["records"]]}
        if not isinstance(entry.get("output"), str) or not isinstance(entry.get("show"), list):
            problems.append(
                f"{where}: 'output' (a path under cv/) and 'show' (a list of record IDs, or \"site\") are required"
            )
            continue
        if (
            entry.get("records") in RECORD_TYPES
            and RECORD_TYPES[entry["records"]].shows_one
            and len(entry["show"]) != 1
        ):
            problems.append(f"{where}: a section of {entry['records']} shows exactly one, so 'show' must list one ID")
        sections.append(
            Section(
                output=CV_DIR / entry["output"],
                records=entry.get("records", ""),
                show=entry["show"],
                omit=entry.get("omit", []),
                compact=entry.get("compact", False),
                follows_site=follows_site,
            )
        )
    if not sections and not problems:
        problems.append(f"{config_file.name}: no [[section]] entries")
    if problems:
        raise SyncError("\n".join(problems))
    return sections


def load_records(records_dir: str) -> dict[str, dict]:
    directory = REPO_ROOT / records_dir
    required = RECORD_TYPES[records_dir].required
    records = {}
    problems = []
    for path in sorted(directory.glob("*.json")):
        try:
            record = json.loads(path.read_text(encoding="utf-8"))
        except json.JSONDecodeError as error:
            problems.append(f"{records_dir}/{path.name}: invalid JSON ({error})")
            continue
        missing = [key for key in required if key not in record]
        if missing:
            problems.append(f"{records_dir}/{path.name}: missing {', '.join(missing)}")
            continue
        records[path.stem] = record
    if problems:
        raise SyncError("\n".join(problems))
    return records


def select_records(section: Section, records: dict[str, dict]) -> list[tuple[str, dict]]:
    """Orders the shown records, failing unless every record is shown or omitted exactly once."""
    name = section.output.relative_to(CV_DIR).as_posix()
    placed = section.show + section.omit
    where = (
        f"the {section.records} list in {DISPLAY_ORDER_FILE.relative_to(REPO_ROOT).as_posix()}"
        if section.follows_site
        else f"this section's 'show' or 'omit' in cv/{CONFIG_FILE.name}"
    )
    problems = [
        f"{name}: '{record_id}' is listed more than once in 'show' and 'omit'"
        for record_id in sorted({record_id for record_id in placed if placed.count(record_id) > 1})
    ]
    problems.extend(
        f"{name}: '{record_id}' is listed, but {section.records}/{record_id}.json does not exist"
        for record_id in placed
        if record_id not in records
    )
    problems.extend(
        f"{name}: {section.records}/{record_id}.json is not placed; add '{record_id}' to {where}"
        for record_id in records
        if record_id not in placed
    )
    if problems:
        raise SyncError("\n".join(problems))
    return [(record_id, records[record_id]) for record_id in section.show]


def render_all() -> dict[Path, str]:
    outputs = {}
    problems = []
    records_by_type: dict[str, dict[str, dict]] = {}
    for section in load_sections(CONFIG_FILE):
        try:
            if section.records not in records_by_type:
                records_by_type[section.records] = load_records(section.records)
            selected = select_records(section, records_by_type[section.records])
        except SyncError as error:
            problems.append(str(error))
            continue
        content = header_comment(section.records) + RECORD_TYPES[section.records].render(selected, section.compact)
        outputs[section.output] = content
    if problems:
        raise SyncError("\n".join(dict.fromkeys(problems)))
    return outputs


def main() -> int:
    try:
        outputs = render_all()
    except SyncError as error:
        print(f"Cannot render the CV from the records:\n{error}", file=sys.stderr)
        return 1
    for path, content in outputs.items():
        path.write_text(content, encoding="utf-8")
    print(f"Rendered {len(outputs)} rubrics under cv/.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
